package com.github.fireprime5.spellcraft.network;

import com.github.fireprime5.spellcraft.energy.MachineEnergy;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Провод как кабель энергии.
 *
 * <p>Сам перенос проверяется в игре: {@link NetworkEnergy#transferEnergy} ходит в
 * capability соседей, а реестр Minecraft в тестах не поднимается. Здесь
 * зафиксированы числа и свойства, из-за которых перенос либо работает, либо
 * нет.
 *
 * <p>История этих тестов — четыре бага, найденных при первой же проверке в
 * игре: энергия исчезала при полном проводе, соседние провода обменивались
 * зарядами вслепую, блок нельзя было поставить рядом с другим, и провод
 * рассыпался в воздухе.
 *
 * <p>Свойства самого блока (replaceable, liquid, требование опоры) тестами не
 * проверяются: реестр Minecraft в тестах не поднимается, а чтение исходников
 * из теста ловит опечатки в путях — так одна проверка падала сама, из-за пути
 * с переставленной буквой в имени пакета: перенос уехал из одного провода в линии сети.
 */
class NetworkEnergyTest {

    @Test
    void проводНеАккумулятор() {
        // если ёмкость провода сравнялась бы с машиной, игрок получал бы
        // бесплатное хранение энергии просто тем, что воткнул линию
        assertTrue(NetworkEnergy.CAPACITY < MachineEnergy.DEFAULT_CAPACITY,
                "ёмкость провода должна быть заметно меньше ёмкости машины");
        assertEquals(1000, NetworkEnergy.CAPACITY);
    }

    @Test
    void запасПроводаМеньшеПолминуты() {
        // извлекатель съедает 4 энергии за тик, то есть 80 в секунду. Запас
        // 1000 единиц — это двенадцать с половиной секунд автономной работы:
        // провод рассчитан на то, чтобы донести энергию, а не накапливать её
        int perSecond = 80;
        double seconds = (double) NetworkEnergy.CAPACITY / perSecond;
        assertTrue(seconds > 5.0 && seconds < 30.0,
                "провод должен держать запас на секунды, а не на минуты");
    }

    @Test
    void переносНеВтыкаетсяНасквозь() {
        // было: брали всегда TRANSFER, а в провод влезало меньше. Разница
        // исчезала — генератор пух, провод не рос. Теперь берётся min(TRANSFER,
        // свободное место), поэтому TRANSFER обязан быть меньше ёмкости.
        assertTrue(NetworkEnergy.TRANSFER > 0, "перенос должен быть положительным");
        assertTrue(NetworkEnergy.TRANSFER <= NetworkEnergy.CAPACITY,
                "за один тик нельзя взять больше, чем в проводе лежит");
    }

    @Test
    void линияДолжнаУспеватьДоставитьЭнергию() {
        // если бы провод отдавал меньше, чем машина съедает, линия не догоняла
        // бы потребление и машина гасла бы при полной энергии на обоих концах
        int extractorPerTick = com.github.fireprime5.spellcraft.energy.AbyssExtractorBlock
                .ENERGY_PER_TICK;
        assertTrue(NetworkEnergy.TRANSFER > extractorPerTick,
                "провод должен подавать больше, чем извлекатель тратит, иначе "
                        + "линия не дотянет");
    }

    @Test
    void скоростьТысячаВСекунду() {
        // выбрано при разговоре: 50 за тик = 1000 в секунду. Линия дотягивает
        // извлекатель (80/с) с двенадцатикратным запасом и не вязнет на
        // машинах Mekanism, которые едят больше
        assertEquals(1000, NetworkEnergy.TRANSFER * 20);
    }

    /**
     * Источники ищутся сквозь цепочку, а не только среди соседей.
     *
     * <p>Это и есть то, что чинит «протянуть далеко». Раньше энергия шла по одному
     * блоку за тик, и сто метров кабеля проходились за двести тиков, а с
     * промежуточными буферами вязла совсем. Теперь потребитель тянет сквозь всю
     * сеть, и длина не имеет значения.
     */
    @Test
    void источникиВидныСквозьСеть() throws Exception {
        var метод = NetworkEnergy.class.getDeclaredMethod("linesThrough",
                net.minecraft.world.level.Level.class,
                net.minecraft.core.BlockPos.class, NetworkLine.class);
        assertTrue(java.lang.reflect.Modifier.isPublic(метод.getModifiers()),
                "обход должен быть виден наружу — иначе его нечем проверить");
    }

    /**
     * Обход ограничен, иначе испорченный мир повесит сервер.
     *
     * <p>Провода, случайно выложенные в спираль, — это миллион блоков в одном
     * компоненте, и обход каждого тика по нему съел бы весь кадр.
     */
    @Test
    void обходОграничен() {
        assertTrue(NetworkEnergy.MAX_SCAN > 0, "предел обхода должен быть положительным");
        assertTrue(NetworkEnergy.MAX_SCAN <= 4096,
                "предел в " + NetworkEnergy.MAX_SCAN + " слишком велик: обход каждого "
                        + "провода станет дороже самой передачи");
    }

    /**
     * Тянуть сквозь сеть можно не каждый тик.
     *
     * <p>Обход всей сети двадцать раз в секунду по каждому проводу — это цена,
     * которую платит вся сеть за удобство одного потребителя. Раз в
     * {@link NetworkEnergy#PULL_INTERVAL} тиков обход идёт в десять раз реже, а
     * потребитель всё равно получает энергию двадцать раз в секунду из запаса.
     */
    @Test
    void тянутьСквозьСетьНеКаждыйТик() {
        assertTrue(NetworkEnergy.PULL_INTERVAL >= 5,
                "обход слишком часто: сеть дорога, а толку от частого обхода "
                        + "почти нет — потребитель берёт из запаса");
        assertTrue(NetworkEnergy.PULL_INTERVAL <= 40,
                "обход слишком редко: линия начнёт «дёргаться» вместо ровной подачи");
    }

    /**
     * Провод не должен накачивать в себя всю сеть.
     *
     * <p>Иначе кабель становится батареей: подключил длинную трассу к источнику —
     * и всю энергию можно вытащить, отключив потребителя.
     */
    @Test
    void тянутьНеБольшеЗапроса() throws Exception {
        String исходник = java.nio.file.Files.readString(java.nio.file.Path.of(
                "src/main/java/com/github/fireprime5/spellcraft/network/NetworkEnergy.java"));
        int начало = исходник.indexOf("public static void pullThrough(");
        assertTrue(начало >= 0, "не найден обход сети в энергии линии");
        String метод = исходник.substring(начало,
                исходник.indexOf("\n    }", начало));
        assertTrue(метод.contains("room"),
                "тянуть надо не больше свободного места, иначе линия станет батареей");
        assertTrue(метод.contains("линия.stored("),
                "обход обязан класть взятое в запас линии");
    }

    @Test
    void запасПроводаНеБольшеОбъёмаПереносаЗаСекунду() {
        // провод — кабель: запас должен покрывать передачу, а не копить её.
        // 1000 единиц — это ровно секунда полной передачи, поэтому линия живёт
        // на источнике, а не на собственном заряде
        assertTrue(NetworkEnergy.CAPACITY <= NetworkEnergy.TRANSFER * 20,
                "запас провода не должен превышать секунду передачи, иначе он "
                        + "превращается в аккумулятор");
    }
}
