package com.github.fireprime5.spellcraft.armor;

import net.minecraft.world.entity.player.Player;

import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Состояние личного модуля «Вечность»: кто сейчас под защитой.
 *
 * <p>Модуль не тикает и не исполняется как заклинание — он висит на нагруднике и
 * отменяет урон из события. Поэтому здесь лежит только «кто включён», а всю работу
 * делает {@link ArmorEvents}.
 *
 * <p>Защита даётся не всем, кому модуль выпал: одновременно её держит не больше
 * {@link #MAX_ACTIVE} игроков. Без потолка шесть владельцев модуля на одном сервере
 * сделали бы «Вечность» обычной бронёй, а личный модуль перестал бы быть редкостью.
 *
 * <p>Класс намеренно ничего не знает про энергию бездны: списание и проверка
 * нехватки живут в {@link ArmorEvents}, чтобы этот класс оставался хранилищем
 * флага. Благодаря этому {@code energy} может спросить «защищён ли игрок», не
 * получив циклическую зависимость на себя.
 */
public final class Eternity {

    /**
     * Сколько игроков одновременно могут держать «Вечность».
     *
     * <p>Константа, а не конфиг: правило «не больше трёх» — часть замысла модуля,
     * а не настройка баланса. Если его сделать настраиваемым, «Вечность» на
     * сервере с лимитом 64 перестанет быть тем, чем задумана.
     */
    public static final int MAX_ACTIVE = 3;

    /**
     * Кто сейчас под «Вечностью», по UUID.
     *
     * <p>Множество, а не флаг в данных игрока: состояние нужно и самому игроку, и
     * подсчёту занятых мест, и проверке «не пора ли выключить защиту». Флаг в
     * persistentData пришлось бы писать на каждый удар и он пережил бы смерть,
     * хотя защита умирать не должна.
     */
    private static final Set<UUID> ACTIVE = ConcurrentHashMap.newKeySet();

/**
     * Пауза, после которой следующий урон считается отдельным ударом, в тиках.
     *
     * <p>Раньше правило было «не чаще раза в 5 тиков» — и это была ошибка: слизень
     * давал четыре единицы за секунду, хотя урон у него один и тот же,
     * непрерывный. А ослабить окно до секунды нельзя было, потому что два
     * настоящих удара зомби в 9 тиков разницы стали бы одним.
     *
     * <p>Значит одного окна мало: время между ударами само по себе не говорит,
     * один это выстрел или продолжение очереди. Различать приходится по
     * плотности: урон, идущий чаще этого интервала, — не очередь ударов, а
     * один непрерывный.
     */
    public static final int ISOLATED_GAP = 5;

    /**
     * Сколько стоит секунда непрерывного урона, в тиках.
     *
     * <p>Слизень касается игрока и бьёт каждый тик: двадцать событий в секунду,
     * все разные. Платить за каждое событие нельзя — это не двадцать ударов, а
     * одно касание. Платить раз в тик тоже нельзя, это и было «как было».
     * Раз в секунду — честная цена одного стояния вплотную.
     */
    public static final int SUSTAINED_INTERVAL = 20;

    /** Когда по этому игроку последний раз прилетел урон и последний раз брали бездну. */
    private record Charge(long lastEvent, long lastCharge) {
    }

    /** Состояние оплаты «Вечности» по UUID игрока. */
    private static final java.util.Map<UUID, Charge> CHARGES =
            new java.util.concurrent.ConcurrentHashMap<>();

    /**
     * Брать ли бездну за этот урон.
     *
     * <p>Два независимых повода заплатить:
     * <ul>
     *   <li>удар <b>отдельный</b> — до предыдущего было не меньше
     *       {@link #ISOLATED_GAP} тиков. Так оплачиваются два настоящих удара
     *       зомби в 9 тиков разницы: это разные удары, а не очередь;
     *   <li>урон <b>непрерывный</b> — но с прошлого раза прошла целая секунда.
     *       Так оплачивается касание слини: ударов там двадцать в секунду, а
     *       платить за него надо раз в секунду.
     * </ul>
     *
     * <p>Метод не только отвечает, но и запоминает урон: вызывать его нужно на
     * каждом событии, даже когда платить не вышло, — иначе очередь слини
     * превратится в двадцать отдельных ударов.
     */
    public static boolean chargeDue(UUID id, long now) {
        Charge прошлый = CHARGES.get(id);
        if (прошлый == null) {
            CHARGES.put(id, new Charge(now, now));
            return true;
        }
        boolean отдельный = now - прошлый.lastEvent() >= ISOLATED_GAP;
        boolean непрерывныйДолжен = now - прошлый.lastCharge() >= SUSTAINED_INTERVAL;
        boolean платить = отдельный || непрерывныйДолжен;
        CHARGES.put(id, new Charge(now, платить ? now : прошлый.lastCharge()));
        return платить;
    }

    /** Состояние игрока после {@link #refresh}. */
    public enum State {
        /** Модуля нет, брони нет или бездны не хватило — защиты нет. */
        OFF,
        /** Защита работает. */
        ACTIVE,
        /** Хочет защиту, но все места заняты. */
        DENIED
    }

    private Eternity() {
    }

    /** Действует ли «Вечность» на игрока прямо сейчас. */
    public static boolean isActive(Player player) {
        return isActive(player.getUUID());
    }

    /**
     * Действует ли «Вечность» на владельца с таким UUID.
     *
     * <p>Ядро сделано на UUID, а не на {@link Player}: всё правило решается по
     * идентификатору, и без сущности оно проверяется обычным тестом. Обёртки выше
     * существуют только ради удобства вызывающего.
     */
    public static boolean isActive(UUID id) {
        return ACTIVE.contains(id);
    }

    /**
     * Пересчитать защиту игрока. Вызывается раз в тик для каждого игрока.
     *
     * @param wants модуль есть на нагруднике, броня запитана, игрок жив
     * @return что в итоге получилось, чтобы вызывающий решил, жаловаться ли игроку
     */
    public static State refresh(Player player, boolean wants) {
        return refresh(player.getUUID(), wants);
    }

    /** То же, что {@link #refresh(Player, boolean)}, но без сущности: см. {@link #isActive(UUID)}. */
    public static State refresh(UUID id, boolean wants) {
        if (!wants) {
            // Сняли нагрудник, разбили броню, списалась бездна или игрок умер —
            // место освобождается сразу, а не по истечении какого-то срока.
            ACTIVE.remove(id);
            return State.OFF;
        }
        if (ACTIVE.contains(id)) {
            return State.ACTIVE;
        }
        if (ACTIVE.size() >= MAX_ACTIVE) {
            return State.DENIED;
        }
        ACTIVE.add(id);
        return State.ACTIVE;
    }

    /**
     * Снять защиту принудительно: бездны не хватило прямо в бою.
     *
     * <p>Место освобождается в том же тике, поэтому освободившийся игрок успевает
     * получить «Вечность» до следующего удара.
     */
    public static void deactivate(Player player) {
        deactivate(player.getUUID());
    }

    /** То же, что {@link #deactivate(Player)}, но без сущности: см. {@link #isActive(UUID)}. */
    public static void deactivate(UUID id) {
        ACTIVE.remove(id);
    }

    /** Сколько мест занято сейчас. */
    public static int activeCount() {
        return ACTIVE.size();
    }

    /** Забыть игрока: смерть, респаун, выход с сервера. */
    public static void clear(UUID id) {
        ACTIVE.remove(id);
        CHARGES.remove(id);
    }

    /** Сбросить всё. Только для тестов. */
    public static void reset() {
        ACTIVE.clear();
        CHARGES.clear();
    }
}