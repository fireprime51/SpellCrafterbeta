package com.github.fireprime5.spellcraft.fluid;

/**
 * Порт энергии бездны: блок, который что-то отдаёт или принимает бездну.
 *
 * <p>Общий интерфейс для труб, бака и машин. Труба не знает, с кем говорит,
 * и не ветвится по типам блоков: она спрашивает интерфейс у соседей. Без
 * этого каждая новая машина требовала бы правок в трубе.
 *
 * <p>Энергия бездны намеренно <b>не</b> Forge-жидкость. Она живёт в трубах и
 * баках мода, но не регистрируется как ванильная жидкость: регистрация
 * потребовала бы отдельной отрисовки жидкости, а пользы не дала бы — в трубы
 * мода всё равно нельзя залить чужую воду, а чужую машину бездной питать не
 * нужно. Если в будущем понадобится настоящая жидкость, порт останется тем же
 * интерфейсом поверх реестра Forge.
 */
public interface AbyssPort {

    /** Сколько энергии бездны лежит сейчас. */
    int abyssStored();

    /** Сколько энергии бездны поместится всего. */
    int abyssCapacity();

    /**
     * Принимает энергию бездны.
     *
     * @param amount сколько предлагается
     * @return сколько реально влезло
     */
    int abyssReceive(int amount);

    /**
     * Отдаёт энергию бездны.
     *
     * @param amount сколько забирают
     * @return сколько реально отдали
     */
    int abyssExtract(int amount);

    /** Есть ли куда ещё принимать. */
    default boolean abyssAccepts() {
        return abyssStored() < abyssCapacity();
    }

    /** Есть ли что отдавать. */
    default boolean abyssProvides() {
        return abyssStored() > 0;
    }

    /**
     * Нужно ли блоку бездны прямо сейчас.
     *
     * <p>Машина отвечает на это по числу включённых модулей: без них машина
     * работает на одной энергии, с ними — ещё и на бездне.
     *
     * @return сколько бездны нужно за тик; 0 — не нужно
     */
    default int abyssDemand() {
        return 0;
    }
}