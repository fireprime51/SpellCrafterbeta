package com.github.fireprime5.spellcraft.network;

import net.minecraft.world.level.block.Block;

/**
 * Отметка блока, который входит в сеть проводов.
 *
 * <p>Провод соединяется не только с проводом. Машина, стоящая вплотную к
 * линии, должна быть её частью: иначе провод к ней не присоединяется, а
 * «Отправить» с лучом на машину падает с «здесь нет провода».
 *
 * <p>Интерфейс, а не проверка «всё, что не воздух», по двум причинам.
 * Во-первых, пустой блок не должен замыкать сеть: зазор в один блок должен
 * разрывать линию. Во-вторых, каждая машина сама решает, участвует ли она в
 * сети, и добавление новой не требует правок в {@link WireBlock}.
 *
 * <p>Пустой интерфейс: это отметка, а не контракт с методами.
 */
public interface NetworkNode {

    /** Блок, который входит в сеть. */
    Block asBlock();
}
