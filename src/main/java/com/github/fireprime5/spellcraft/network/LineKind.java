package com.github.fireprime5.spellcraft.network;

import java.util.Locale;

/**
 * Вид линии: по виду она ищет соседей и берёт ресурс.
 *
 * <p>Энергия и жидкость — разные валюты, и путать их в одном блоке нельзя: иначе
 * труба начнёт тянуть Forge Energy, а энергетическая труба — жидкость, и игрок
 * получит сеть, которая работает через раз.
 *
 * <p>Цвет есть только у энергетической линии (см. {@link NetworkLine}): труба
 * жидкости цветом не делится, у неё своя жидкость, и она различает линии.
 */
public enum LineKind {

    /** Провод: Forge Energy, цвет разделяет сети. */
    ENERGY,

    /**
     * Труба жидкости: переносит то, чем заполнена.
     *
     * <p>Жидкость линии узнаёт не предмет, а сосед: труба одна на все жидкости,
     * и какой она — видно по тому, к чему подключилась. Поэтому вид не делится
     * цветом, как провод, и не имеет шестнадцати вариантов.
     */
    FLUID;

    /** Имя для NBT и переводов: всегда строчное, всегда латиницей. */
    public String id() {
        return name().toLowerCase(Locale.ROOT);
    }

    /** Линия по имени из NBT. Битое имя читается как {@link #ENERGY}. */
    public static LineKind byId(String id) {
        for (LineKind kind : values()) {
            if (kind.id().equals(id)) {
                return kind;
            }
        }
        return ENERGY;
    }
}
