#!/usr/bin/env python3
"""Собирает CODE_INDEX.md: путь к каждому исходнику и короткое описание.

Описание берётся из javadoc типа: первый абзац — это и есть короткий ответ на
вопрос «что в файле». Отдельный разбор тела класса нужен только трём файлам без
описания, поэтому он делается глазами и вписывается вручную.
"""

import re
import subprocess
from pathlib import Path

ОСНОВНОЕ = "src/main/java"
ТЕСТЫ = "src/test/java"
ТИПЫ = r'(?:public\s+|final\s+|abstract\s+|sealed\s+|static\s+)*(class|record|enum|interface|@interface)\s+(\w+)'

# Файлы без javadoc: описание дописано руками, по трём штукам.
ВРУЧНУЮ = {
    "Spellcraft.java": "Общие константы мода и логгер: идентификатор, версия, "
                       "имя логгера. Место, куда сходятся все общие для пакета вещи.",
    "SpellcraftMod.java": "Точка входа мода: регистрирует блоки, предметы, меню, "
                          "события общей шины и capability энергии и жидкости.",
    "SpellcraftPayload.java": "Общая база сетевых пакетов: правила кодирования и "
                              "проверки, общие для всех сообщений клиент↔сервер.",
    "ClientBridgeInstaller.java": "Мост между клиентским кодом мода и NeoForge: "
                                  "регистрирует клавиши, экраны, блочные рендереры "
                                  "и сетевые обработчики. Единственное место, где "
                                  "клиентская часть цепляется к шине событий.",
    "ClientRuntimeEvents.java": "Клиентские события вне установщика: тик клиента и "
                                "прочее, что не требует регистрации через шину.",
    "ModCreativeTabs.java": "Содержимое креативной вкладки мода: блоки, предметы и "
                            "то, что показывается только при включённой отладке.",
    "ModItems.java": "Реестр предметов мода: гримуар, броня, машины и предметы "
                     "линий. Все id пишутся литералами — реестр проверяется тестом.",
}

ПУСТЫЕ_СЕКЦИИ = re.compile(r'^\s*(public|protected|private)?\s*(static\s+)?(final\s+)?[\w<>\[\],.?\s]+\s+(\w+)\s*\(')


def склонение(число: int) -> str:
    """«1 строка», «2 строки», «5 строк»: без этого шапка выглядит грамматически."""
    if число % 100 in (11, 12, 13, 14):
        return "строк"
    остаток = число % 10
    return "строка" if остаток == 1 else ("строки" if остаток in (2, 3, 4) else "строк")


def первый_абзац(текст: str) -> str:
    """Первый абзац javadoc: до пустой строки, теги и @-строки убираются."""
    строки = []
    for строка in текст.splitlines():
        строка = строка.strip()
        if строка.startswith("*"):
            строка = строка.lstrip("*").strip()
        if строка.startswith("@"):
            break
        if not строка:
            if строки:
                break
            continue
        строка = re.sub(r'\{@\w+\s+([^}]*)\}', r'\1', строка)
        строки.append(строка)
    абзац = " ".join(строки).strip()
    абзац = re.sub(r'<\/?[a-z][^>]*>', ' ', абзац)
    абзац = re.sub(r'\s+', ' ', абзац).strip()
    return абзац


def два_абзаца(текст: str) -> str:
    """Первый абзац, а если он короткий — ещё и следующий: одной строки мало."""
    целиком = re.sub(r'\n\s*\*', '\n', текст)
    целиком = re.sub(r'\n\s*\n\s*\n', '\n\n', целиком)
    абзацы = [p.strip() for p in целиком.split('\n\n') if p.strip()]
    первый = первый_абзац(абзацы[0]) if абзацы else ''
    if len(первый) < 70 and len(абзацы) > 1:
        второй = первый_абзац(абзацы[1])
        if второй and len(второй) < 400:
            первый = первый + ' ' + второй
    return первый


def описание(путь: str) -> str:
    ключ = путь.split('/')[-1]
    if ключ in ВРУЧНУЮ:
        return ВРУЧНУЮ[ключ]
    текст = Path(путь).read_text(encoding='utf-8')
    совпадение = re.search(r'/\*\*(.*?)\*/\s*' + ТИПЫ, текст, re.S)
    if совпадение:
        абзац = два_абзаца(совпадение.group(1))
        if len(абзац) > 30:
            return абзац.rstrip('.') + '.' if not абзац.endswith('.') else абзац
    # запасной путь: имя класса словами плюс публичные методы
    имя = re.search(ТИПЫ, текст)
    if имя:
        слова = re.findall(r'[A-ZА-Я][a-zа-я0-9]*|[a-zа-я0-9]+',
                           имя.group(2))
        хвост = " ".join(слова).lower()
        методы = re.findall(r'\n\s+public\s+(?:static\s+)?(?:final\s+)?[\w<>\[\],.?\s]+?\s+(\w+)\s*\(',
                            текст)
        уникальные = []
        for м in методы:
            if м not in уникальные and м not in ('equals', 'hashCode', 'toString'):
                уникальные.append(м)
        основа = f"{хвост.capitalize()}"
        if уникальные[:6]:
            основа += "; методы: " + ", ".join(уникальные[:6])
        return основа + "."
    return "Служебный файл без описания."


def шапка(путь: str) -> str:
    текст = Path(путь).read_text(encoding='utf-8')
    пакет = re.search(r'^package\s+([\w.]+);', текст, re.M)
    строка = len(текст.splitlines())
    имя = re.search(ТИПЫ, текст)
    вид = {"class": "класс", "record": "запись", "enum": "перечисление",
           "interface": "интерфейс", "@interface": "аннотация"}
    тип = вид.get(имя.group(1), имя.group(1)) if имя else "файл"
    адрес = f", пакет `{пакет.group(1)}`" if пакет else ""
    return (f"{тип} `{имя.group(2) if имя else '?'}`{адрес} — "
            f"{строка} {склонение(строка)}")


def раздел(корень: str) -> list:
    файлы = subprocess.check_output(
        ['bash', '-c', f'find {корень} -name "*.java" | sort'], text=True
    ).strip().split('\n')
    строки = []
    for путь in файлы:
        строки.append(f"### `{путь[len(корень) + 1:]}`")
        строки.append("")
        строки.append(шапка(путь))
        строки.append("")
        строки.append(описание(путь))
        строки.append("")
    return строки


def собрать() -> str:
    части = [
        "# Карта кода",
        "",
        "Путь к каждому исходнику и коротко о том, что в нём находится. Порядок",
        "совпадает с деревом пакетов, так что по названию файла можно догадаться,",
        "где искать остальное. Подробности — в javadoc самого файла.",
        "",
    ]
    части += ["## Основной код", ""]
    части += раздел(ОСНОВНОЕ)
    части += ["## Тесты", "",
              "Тесты не поднимают Minecraft: проверяется то, что можно проверить",
              "без мира, — правила, кодеки, ассеты и структура исходников. Всё, что",
              "ходит в мир, проверяется в игре.", ""]
    части += раздел(ТЕСТЫ)
    return "\n".join(части) + "\n"


if __name__ == "__main__":
    Path("CODE_INDEX.md").write_text(собрать(), encoding='utf-8')
    print("CODE_INDEX.md готов")
